inline UnicodeCat unicode_cat(uint32_t cp) {
    if (cp < 0x80u) {
        if ((cp >= 'A' && cp <= 'Z') || (cp >= 'a' && cp <= 'z')) return UC_LETTER;
        if (cp >= '0' && cp <= '9') return UC_NUMBER;
        if (cp == ' ' || (cp >= 0x09u && cp <= 0x0Du)) return UC_SPACE;
        return UC_OTHER;
    }
    if (cp > 0x10FFFFu) return UC_OTHER;
    const uint32_t key = (cp << 3) | 7u;
    constexpr size_t N = sizeof(kUnicodeCatRuns) / sizeof(kUnicodeCatRuns[0]);
    const uint32_t * it = std::upper_bound(kUnicodeCatRuns, kUnicodeCatRuns + N, key);
    if (it == kUnicodeCatRuns) return UC_OTHER;
    return static_cast<UnicodeCat>((*(it - 1)) & 7u);
}

